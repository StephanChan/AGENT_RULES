# tools/sync-global.ps1 - Windows equivalent of tools/sync-global.sh (PowerShell 5.1+, no bash needed).
#
# NOTE: this file is pure ASCII on purpose. Windows PowerShell 5.1 decodes BOM-less .ps1 as ANSI,
#       so non-ASCII text here would break parsing; the repo lint also forbids a BOM.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools\sync-global.ps1 -RulesDir <cline global rules dir> [-Force]
#   $env:CLINE_GLOBAL_RULES_DIR = '<path>'; powershell -ExecutionPolicy Bypass -File tools\sync-global.ps1
#   Python not on PATH (Anaconda): -PythonPath 'D:\Anaconda\python.exe'
#
# Where the global rules dir is: visible/creatable in Cline's Rules panel (the official docs give no
# fixed path, so this script does not guess).
#
# Behavior (idempotent, mirrors tools/sync-global.sh):
#   1) runs python tools/check_rules.py and aborts when it fails;
#   2) creates/checks $HOME\.agent-rules -> repo root as a directory junction (no admin needed);
#   3) copies .clinerules\00-agent-rules.md into the global rules dir with an "auto-generated" marker
#      on the first line; an existing file that was not produced by this tool is never overwritten
#      unless -Force. Bytes are copied verbatim, so the LF line endings of the source are preserved.
#
# Exit codes: 0 success / 1 usage or environment error / 2 rule check failed / 3 refused to overwrite
[CmdletBinding()]
param(
    [Parameter(Position = 0)][string]$RulesDir = $env:CLINE_GLOBAL_RULES_DIR,
    [string]$PythonPath = '',
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

function Get-PythonExe {
    param([string]$Explicit)
    if ($Explicit) {
        if (-not (Test-Path $Explicit)) { throw "python not found: $Explicit" }
        return $Explicit
    }
    foreach ($name in @('python', 'python3')) {
        $cmd = Get-Command $name -ErrorAction SilentlyContinue | Select-Object -First 1
        # skip the Microsoft Store stub aliases (they print "Python was not found")
        if ($cmd -and $cmd.Source -notmatch 'WindowsApps') { return $cmd.Source }
    }
    throw 'python not found on PATH; with Anaconda pass -PythonPath (e.g. -PythonPath D:\Anaconda\python.exe)'
}

$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$Link = Join-Path $HOME '.agent-rules'
$Src = Join-Path $Repo '.clinerules\00-agent-rules.md'
$MarkerText = "<!-- AUTO-GENERATED by tools/sync-global.ps1; do not edit here, edit $Repo/.clinerules/00-agent-rules.md -->"
$MarkerGrep = 'tools/sync-global'

if (-not $RulesDir) {
    [Console]::Error.WriteLine('Usage: tools\sync-global.ps1 -RulesDir <cline global rules dir> [-Force]')
    [Console]::Error.WriteLine('  The global rules dir is the one shown/created in Cline''s Rules panel; CLINE_GLOBAL_RULES_DIR also works.')
    exit 1
}
if (-not (Test-Path $Src)) {
    [Console]::Error.WriteLine("not found: $Src")
    exit 1
}

try {
    $Python = Get-PythonExe -Explicit $PythonPath
} catch {
    [Console]::Error.WriteLine($_.Exception.Message)
    exit 1
}

Write-Host '[1/3] Checking rule files'
& $Python (Join-Path $Repo 'tools\check_rules.py')
if ($LASTEXITCODE -ne 0) {
    [Console]::Error.WriteLine('Rule check failed; fix the rules before syncing.')
    exit 2
}

Write-Host "[2/3] Pinning path: $Link -> $Repo"
if (Test-Path $Link) {
    $item = Get-Item -LiteralPath $Link -Force
    $target = @($item.Target)[0]
    if ($item.LinkType -and $target -eq $Repo) {
        Write-Host '  already in place'
    } elseif ($item.LinkType) {
        Write-Warning "$Link points to $target, not this repo; delete it yourself if you want to repoint."
    } else {
        Write-Warning "$Link exists and is not a link; skipped (left untouched)."
    }
} else {
    New-Item -ItemType Junction -Path $Link -Target $Repo | Out-Null
    Write-Host '  created'
}

Write-Host "[3/3] Syncing to global rules dir: $RulesDir"
New-Item -ItemType Directory -Path $RulesDir -Force | Out-Null
$Dest = Join-Path $RulesDir '00-agent-rules.md'
if ((Test-Path $Dest) -and (-not $Force)) {
    $firstLine = Get-Content -LiteralPath $Dest -TotalCount 1 -Encoding UTF8
    if ($firstLine -notmatch [regex]::Escape($MarkerGrep)) {
        [Console]::Error.WriteLine("  refused to overwrite: $Dest was not generated by this tool (use -Force to override).")
        exit 3
    }
}
$markerBytes = [System.Text.Encoding]::UTF8.GetBytes($MarkerText + "`n")
$srcBytes = [System.IO.File]::ReadAllBytes($Src)
$stream = [System.IO.File]::Create($Dest)
try {
    $stream.Write($markerBytes, 0, $markerBytes.Length)
    $stream.Write($srcBytes, 0, $srcBytes.Length)
} finally {
    $stream.Dispose()
}
$lineCount = ([System.IO.File]::ReadAllText($Dest).Split("`n")).Count - 1
Write-Host "  done: $Dest ($lineCount lines)"

Write-Host ''
Write-Host "Next: paste the three lines of $Repo\CLINE_CUSTOM_INSTRUCTIONS.md into Cline's global Custom Instructions;"
Write-Host "      <RULES_DIR> = $Link (or $Repo)."
exit 0
